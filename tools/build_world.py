"""
build_world.py - Generate worlds/campus.wbt from campus_layout.py.

Run from the InteliPatrol folder:
    python tools/build_world.py
"""
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "controllers", "patrol_controller"))
import campus_layout as L  # noqa: E402


def slug(name):
    return name.lower().replace(" ", "_")


def colour(c):
    return "%.2f %.2f %.2f" % c


def box_solid(name, cx, cy, sx, sy, h, col, solid=True, z0=0.0):
    geom = "Box { size %.3f %.3f %.3f }" % (sx, sy, h)
    bo = "\n  boundingObject %s" % geom if solid else ""
    return """Solid {
  translation %.3f %.3f %.3f
  name "%s"
  children [
    Shape {
      appearance PBRAppearance { baseColor %s roughness 0.9 metalness 0 }
      geometry %s
    }
  ]%s
}
""" % (cx, cy, z0 + h / 2, name, colour(col), geom, bo)


def building(name, cx, cy, sx, sy, h, col):
    """A building: main block + darker roof slab + a door on the south side."""
    s = """Solid {
  translation %.3f %.3f %.3f
  name "building_%s"
  children [
    Shape {
      appearance PBRAppearance { baseColor %s roughness 0.9 metalness 0 }
      geometry Box { size %.3f %.3f %.3f }
    }
    Pose {
      translation 0 0 %.3f
      children [
        Shape {
          appearance PBRAppearance { baseColor 0.3 0.3 0.32 roughness 0.8 metalness 0 }
          geometry Box { size %.3f %.3f 0.2 }
        }
      ]
    }
""" % (cx, cy, h / 2, slug(name), colour(col), sx, sy, h, h / 2 + 0.1, sx + 0.2, sy + 0.2)
    # window strips on every floor (visual only)
    floors = max(1, int(h // 3))
    for f in range(floors):
        z = -h / 2 + 1.6 + f * 3.0
        if z > h / 2 - 0.8:
            break
        s += """    Pose {
      translation 0 0 %.3f
      children [
        Shape {
          appearance PBRAppearance { baseColor 0.35 0.55 0.75 roughness 0.2 metalness 0.4 }
          geometry Box { size %.3f %.3f 0.9 }
        }
        Shape {
          appearance PBRAppearance { baseColor 0.35 0.55 0.75 roughness 0.2 metalness 0.4 }
          geometry Box { size %.3f %.3f 0.9 }
        }
      ]
    }
""" % (z, sx + 0.02, max(0.1, sy - 1.0), max(0.1, sx - 1.0), sy + 0.02)
    s += """  ]
  boundingObject Box { size %.3f %.3f %.3f }
}
""" % (sx, sy, h)
    return s


def tree(k, x, y):
    return """Solid {
  translation %.3f %.3f 1.25
  name "tree_%d"
  children [
    Shape {
      appearance PBRAppearance { baseColor 0.4 0.26 0.13 roughness 1 metalness 0 }
      geometry Cylinder { height 2.5 radius %.2f subdivision 10 }
    }
    Pose {
      translation 0 0 1.8
      children [
        Shape {
          appearance PBRAppearance { baseColor 0.16 0.45 0.16 roughness 1 metalness 0 }
          geometry Sphere { radius 1.3 subdivision 2 }
        }
      ]
    }
  ]
  boundingObject Cylinder { height 2.5 radius %.2f }
}
""" % (x, y, k, L.TREE_TRUNK_RADIUS, L.TREE_TRUNK_RADIUS)


def main():
    out = ["""#VRML_SIM R2025a utf8
# InteliPatrol campus - GENERATED by tools/build_world.py from campus_layout.py

EXTERNPROTO "../protos/PatrolBot.proto"
EXTERNPROTO "https://raw.githubusercontent.com/cyberbotics/webots/R2025a/projects/humans/pedestrian/protos/Pedestrian.proto"

WorldInfo {
  info [ "InteliPatrol: AI-Based Autonomous Campus Monitoring System" ]
  title "InteliPatrol Campus"
  basicTimeStep 32
}
Viewpoint {
  orientation 0 1 0 0.95
  position -27 0 36
}
Background {
  skyColor [ 0.55 0.72 0.9 ]
}
DirectionalLight {
  ambientIntensity 0.6
  direction -0.4 -0.6 -1
  intensity 2.2
  castShadows FALSE
}
"""]
    h = L.WORLD_HALF
    # ground
    out.append(box_solid("ground", 0, 0, 2 * h + 4, 2 * h + 4, 0.1, (0.36, 0.56, 0.30), z0=-0.1))
    # visual-only ground markings
    for name, (cx, cy), (sx, sy), col in L.ROADS:
        out.append(box_solid(name, cx, cy, sx, sy, 0.004, col, solid=False))
    (cx, cy), (sx, sy), col = L.SPORTS_GROUND
    out.append(box_solid("sports_ground", cx, cy, sx, sy, 0.008, col, solid=False))
    for k, (dname, (dx, dy)) in enumerate(getattr(L, "DOCKS", [L.DOCK])):
        out.append(box_solid("charging_dock_pad_%d" % (k + 1), dx, dy, 1.4, 1.4, 0.012,
                             (0.1, 0.75, 0.3), solid=False))
    # checkpoint markers (visual only)
    for k, (name, (x, y)) in enumerate(L.CHECKPOINTS):
        out.append(box_solid("checkpoint_%d_%s" % (k + 1, slug(name)), x, y, 0.8, 0.8, 0.012,
                             (0.95, 0.85, 0.1), solid=False))
    # perimeter walls
    t, wh = L.WALL_THICKNESS, L.WALL_HEIGHT
    for name, cx, cy, sx, sy in [("wall_north", 0, h, 2 * h + t, t), ("wall_south", 0, -h, 2 * h + t, t),
                                 ("wall_east", h, 0, t, 2 * h), ("wall_west", -h, 0, t, 2 * h)]:
        out.append(box_solid(name, cx, cy, sx, sy, wh, (0.75, 0.72, 0.68)))
    # buildings
    for name, (cx, cy), (sx, sy), bh, col in L.BUILDINGS:
        out.append(building(name, cx, cy, sx, sy, bh, col))
    # trees and benches
    for k, (x, y) in enumerate(L.TREES):
        out.append(tree(k + 1, x, y))
    for k, ((cx, cy), (sx, sy)) in enumerate(L.BENCHES):
        out.append(box_solid("bench_%d" % (k + 1), cx, cy, sx, sy, L.BENCH_HEIGHT, (0.55, 0.35, 0.2)))
    # obstacles the robot does not know about
    for name, (cx, cy), (sx, sy), oh, col in L.UNMAPPED_OBSTACLES:
        out.append(box_solid(slug(name), cx, cy, sx, sy, oh, col))
    # people walking around campus (Layer 2)
    for name, traj, speed, shirt in getattr(L, "PEDESTRIANS", []):
        tr = ", ".join("%.2f %.2f" % p for p in traj)
        out.append("""Pedestrian {
  translation %.2f %.2f 1.27
  name "%s"
  controllerArgs [ "--trajectory=%s" "--speed=%.2f" ]
  shirtColor %s
}
""" % (traj[0][0], traj[0][1], name, tr, speed, colour(shirt)))
    # the unattended suitcase: body + handle + wheels (not on the robot's map)
    if hasattr(L, "SUITCASE"):
        name, (sx, sy) = L.SUITCASE
        out.append("""Solid {
  translation %.2f %.2f 0.37
  rotation 0 0 1 0.4
  name "%s"
  children [
    Shape {
      appearance PBRAppearance { baseColor 0.55 0.08 0.1 roughness 0.5 metalness 0.1 }
      geometry Box { size 0.45 0.25 0.62 }
    }
    Pose { translation 0 0 0.33 children [ Shape {
      appearance PBRAppearance { baseColor 0.1 0.1 0.1 roughness 0.4 metalness 0.6 }
      geometry Box { size 0.2 0.03 0.08 } } ] }
    Pose { translation 0.17 0 -0.33 rotation 1 0 0 1.5708 children [ Shape {
      appearance PBRAppearance { baseColor 0.05 0.05 0.05 roughness 0.9 metalness 0 }
      geometry Cylinder { height 0.27 radius 0.04 } } ] }
    Pose { translation -0.17 0 -0.33 rotation 1 0 0 1.5708 children [ Shape {
      appearance PBRAppearance { baseColor 0.05 0.05 0.05 roughness 0.9 metalness 0 }
      geometry Cylinder { height 0.27 radius 0.04 } } ] }
  ]
  boundingObject Box { size 0.45 0.25 0.7 }
}
""" % (sx, sy, name))
    # the robot fleet
    fleet = getattr(L, "FLEET", None) or [{"name": "patrolbot_1", "route": list(range(len(L.CHECKPOINTS))),
                                           "dock": 0, "battery": 100, "start": L.ROBOT_START,
                                           "color": (0.12, 0.32, 0.78)}]
    for k, r in enumerate(fleet):
        x, y, yaw = r["start"]
        args = '"--route=%s" "--dock=%d" "--battery=%d" "--priority=%d"' % (
            ",".join(str(c) for c in r["route"]), r["dock"], r["battery"], k + 1)
        out.append("""PatrolBot {
  translation %.3f %.3f 0.11
  rotation 0 0 1 %.4f
  name "%s"
  controller "patrol_controller"
  controllerArgs [ %s ]
  bodyColor %s
}
""" % (x, y, yaw, r["name"], args, colour(r["color"])))

    path = os.path.join(ROOT, "worlds", "campus.wbt")
    with open(path, "w") as f:
        f.write("".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
